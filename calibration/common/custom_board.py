"""Support for a custom (not OpenCV-generated) marker-grid board -- i.e. a
board you already have, where markers sit at known positions but the
board doesn't necessarily follow OpenCV's own CharucoBoard layout
convention. Rather than risk silently guessing that convention wrong (which
would corrupt every calibration downstream with no obvious symptom),
calibration/common/charuco_compat.py's CharucoBoard path is reserved for
boards actually generated by board/generate_charuco_board.py, where the
layout is known for certain; this module is for everything else.

The layout file (config/custom_board_layout.yaml) is built once per board
by directly inspecting a reference photo together with cv2.aruco's raw
marker detections -- see docs/BUILDING_A_CUSTOM_BOARD_LAYOUT.md for exactly
how. It is NOT inferred automatically by clustering marker pixel positions
in this module: that's a much easier way to get a subtly, silently wrong
grid mapping than to just look at one photo directly.

Calibration still only needs ArUco marker corners (not interpolated
checkerboard corners) -- a plain ArUco marker gives 4 known 3D corners and
4 detected 2D corners per marker per frame, which is plenty for both
camera intrinsic calibration (cv2.calibrateCamera, generic -- not the
charuco-specific variant) and PnP-based pose/extrinsic solving. The only
real precision cost vs. true ChArUco is not having the extra sub-pixel
interior-corner interpolation step; marker-corner-only calibration is still
a standard, correct technique on its own (it's exactly what
cv2.aruco.calibrateCameraAruco / a generic ArUco GridBoard does).
"""
import cv2
import numpy as np
import yaml

USING_NEW_API = hasattr(cv2.aruco, 'ArucoDetector')


def load_layout(path):
    """Returns (dictionary, {marker_id: 4x3 float array of object-frame
    corner points, in the same TL/TR/BR/BL order ArUco detection returns})."""
    with open(path) as f:
        cfg = yaml.safe_load(f)
    dict_id = getattr(cv2.aruco, cfg['dictionary'])
    dictionary = cv2.aruco.getPredefinedDictionary(dict_id)
    layout = {int(m['id']): np.array(m['corners_3d'], dtype=np.float64) for m in cfg['markers']}
    return dictionary, layout


def detect_markers(gray_image, dictionary):
    """Returns (corners, ids) via plain ArUco detection -- corners is a
    list of 1x4x2 float32 arrays (one per detected marker, TL/TR/BR/BL
    pixel order), ids is Nx1 int array. Either may be empty if nothing
    found."""
    if USING_NEW_API:
        params = cv2.aruco.DetectorParameters()
        detector = cv2.aruco.ArucoDetector(dictionary, params)
        corners, ids, _rejected = detector.detectMarkers(gray_image)
    else:
        params = cv2.aruco.DetectorParameters_create()
        corners, ids, _rejected = cv2.aruco.detectMarkers(gray_image, dictionary, parameters=params)
    return corners, ids


def correspondences_for_frame(corners, ids, layout):
    """Flattens all markers that are BOTH detected in this frame AND
    present in the known layout into one set of 3D object points + 2D
    image points, ready for cv2.calibrateCamera / cv2.solvePnP. Markers
    detected but not in the layout (e.g. a stray marker in the background)
    are silently ignored, not errored on."""
    obj_pts, img_pts = [], []
    if ids is None:
        return np.zeros((0, 3)), np.zeros((0, 2))
    for corner, marker_id in zip(corners, ids.flatten()):
        if marker_id not in layout:
            continue
        obj_pts.append(layout[marker_id])
        img_pts.append(corner.reshape(4, 2))
    if not obj_pts:
        return np.zeros((0, 3)), np.zeros((0, 2))
    return np.concatenate(obj_pts, axis=0), np.concatenate(img_pts, axis=0)


def board_plane_pose(obj_pts, img_pts, camera_matrix, dist_coeffs):
    """PnP solve for the board's pose in the camera frame, then the
    resulting plane normal/distance -- same shape of result as
    lidar_camera_extrinsic.py's board_pose_from_image, so that script
    works unmodified with either board type (see its --board-type flag)."""
    if len(obj_pts) < 4:
        return None
    ok, rvec, tvec = cv2.solvePnP(obj_pts.astype(np.float32), img_pts.astype(np.float32),
                                   camera_matrix, dist_coeffs)
    if not ok:
        return None
    R_board_to_cam, _ = cv2.Rodrigues(rvec)
    normal_cam = R_board_to_cam @ np.array([0, 0, 1.0])
    tvec = tvec.flatten()
    d_cam = normal_cam @ tvec
    return normal_cam, d_cam, rvec, tvec
